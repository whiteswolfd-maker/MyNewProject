def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def _flatten_grads(params, grads) -> torch.Tensor:
    parts = []
    for param, grad in zip(params, grads):
        if grad is None:
            parts.append(torch.zeros_like(param).reshape(-1))
        else:
            parts.append(grad.reshape(-1))
    return torch.cat(parts)


def _grad_metrics(g_ic: torch.Tensor, g_full: torch.Tensor) -> dict:
    g_other = g_full - g_ic
    norm_ic = float(torch.linalg.vector_norm(g_ic))
    norm_full = float(torch.linalg.vector_norm(g_full))
    norm_other = float(torch.linalg.vector_norm(g_other))
    dot = float(torch.dot(g_ic, g_full))
    denom = max(norm_ic * norm_full, 1.0e-300)
    return {
        "norm_ic": norm_ic,
        "norm_full": norm_full,
        "norm_other_terms": norm_other,
        "norm_ic_over_norm_full": norm_ic / max(norm_full, 1.0e-300),
        "cosine_ic_full": dot / denom,
        "projection_fraction_on_full": dot / max(norm_full * norm_full, 1.0e-300),
        "relative_residual_after_removing_ic": norm_other / max(norm_full, 1.0e-300),
        "cosine_ic_other": float(
            torch.dot(g_ic, g_other)
            / max(norm_ic * norm_other, 1.0e-300)
        ),
    }


def _block_norms(net, grads) -> dict:
    result = {"trunk": 0.0, "head_rho": 0.0, "head_u": 0.0, "head_p": 0.0}
    for (name, _), grad in zip(net.named_parameters(), grads):
        if grad is None:
            continue
        if name.startswith("trunk."):
            result["trunk"] += float(torch.sum(grad * grad))
        elif name.startswith("head_rho."):
            result["head_rho"] += float(torch.sum(grad * grad))
        elif name.startswith("head_u."):
            result["head_u"] += float(torch.sum(grad * grad))
        elif name.startswith("head_p."):
            result["head_p"] += float(torch.sum(grad * grad))
    return {key: math.sqrt(value) for key, value in result.items()}


def _batch_hash(batches) -> str:
    digest = hashlib.sha256()
    for case, batch in batches:
        digest.update(case.case_id.encode("utf-8"))
        for name in (
            "t_pde", "zeta_pde", "t_ic", "zeta_ic", "t_right", "t_data",
            "radius_data", "rho_data", "u_data", "p_data", "valid_rho",
            "valid_u", "valid_p", "t_contact", "low_contact", "up_contact",
        ):
            value = getattr(batch, name)
            array = np.ascontiguousarray(value.detach().cpu().numpy())
            digest.update(name.encode("ascii"))
            digest.update(str(array.shape).encode("ascii"))
            digest.update(array.tobytes())
    return digest.hexdigest()


def _air_terms(trainer, batches, loop: int):
    """Reproduce the AirNet-stage terms without backward or an optimizer step."""
    lambda_pde, lambda_data = schedule_weights(loop, trainer.config.n_schedule)
    per_case = []
    for case, batch in batches:
        closure = trainer._closures[case.case_id]
        scales = trainer._scales[case.case_id]
        r0, rs, ds = trainer._contact_inputs(case, batch.t_pde)
        contact = trainer.contact_net(
            batch.t_pde.reshape(-1, 1), r0, rs, ds, closure,
            time_input=case.time_input, create_graph=False,
        )
        contact = _detach_contact(contact)
        geometry = build_geometry(
            contact.radius, contact.speed, rs, ds,
            batch.zeta_pde.reshape(-1, 1),
        )
        fields, derivatives = air_fields_with_derivatives(
            trainer.air_net, batch.zeta_pde, batch.t_pde, r0, scales,
            create_graph=True, time_input=case.time_input,
        )
        pde = pde_loss(
            fields=fields, derivatives=derivatives, geometry=geometry, case=case
        )
        ic = air_ic_loss(trainer.air_net, batch, case, scales)
        if batch.t_pde.numel():
            air0 = trainer.air_net(
                torch.zeros_like(batch.t_pde).reshape(-1, 1),
                batch.t_pde.reshape(-1, 1), r0.reshape(-1, 1), scales,
                time_input=case.time_input,
            )
            interface = interface_loss(
                air_at_contact=air0, contact=contact, case=case
            )
        else:
            interface = None
        right = right_loss(
            net=trainer.air_net, batch=batch, case=case, scales=scales
        )
        if batch.t_data.numel():
            r0d, rsd, dsd = trainer._contact_inputs(case, batch.t_data)
            c_data = trainer.contact_net(
                batch.t_data.reshape(-1, 1), r0d, rsd, dsd, closure,
                time_input=case.time_input, create_graph=False,
            )
            c_data = _detach_contact(c_data)
            data = air_data_loss(
                trainer.air_net, batch, case, scales, c_data
            )
        else:
            data = None
        if interface is None:
            interface = type(ic)(
                total=torch.zeros((), dtype=torch.float64),
                counts={"interface": 0}, parts={"interface": 0.0},
            )
        if data is None:
            data = type(ic)(
                total=torch.zeros((), dtype=torch.float64),
                counts={"data": 0}, parts={"data": 0.0},
            )
        combined = combine_air(
            pde=pde, ic=ic, interface=interface, right=right, data=data,
            lambda_pde=lambda_pde, lambda_data=lambda_data,
        )
        per_case.append({
            "case_id": case.case_id,
            "pde": pde,
            "ic": ic,
            "interface": interface,
            "right": right,
            "data": data,
            "combined": combined,
        })
    return lambda_pde, lambda_data, per_case


def _loss_record(lambda_pde, lambda_data, per_case) -> dict:
    n = len(per_case)
    raw = {}
    weighted = {}
    for key in ("pde", "ic", "interface", "right", "data"):
        raw[key] = float(
            sum(float(row[key].total.detach()) for row in per_case) / n
        )
    weighted["pde"] = lambda_pde * raw["pde"]
    weighted["data"] = lambda_data * raw["data"]
    weighted["ic"] = raw["ic"]  # combine_air uses weight 1.0
    weighted["interface"] = raw["interface"]
    weighted["right"] = raw["right"]
    total = float(
        sum(float(row["combined"].total.detach()) for row in per_case) / n
    )
    return {
        # ``data`` is now the theta-cell-weighted air data loss; the other
        # terms remain unweighted.  Keep the semantics explicit for readers of
        # old and new JSON files.
        "term_values": raw,
        "term_value_semantics": {
            "data": "theta_cell_weighted",
            "pde": "unweighted",
            "ic": "unweighted",
            "interface": "unweighted",
            "right": "unweighted",
        },
        "phase_weighting": "uniform",
        "weighted_contribution": weighted,
        "total": total,
        "ic_share_of_total": weighted["ic"] / max(abs(total), 1.0e-300),
        "lambda_pde": float(lambda_pde),
        "lambda_data": float(lambda_data),
        "ic_weight": 1.0,
        "n_cases": n,
    }


def _gradient_record(
    trainer, per_case,
) -> tuple[dict, torch.Tensor, torch.Tensor]:
    params = [p for p in trainer.air_net.parameters()]
    n = len(per_case)
    loss_ic = sum(row["ic"].total for row in per_case) / n
    loss_full = sum(row["combined"].total for row in per_case) / n
    grads_ic = torch.autograd.grad(
        loss_ic, params, retain_graph=True, allow_unused=True
    )
    grads_full = torch.autograd.grad(
        loss_full, params, retain_graph=False, allow_unused=True
    )
    g_ic = _flatten_grads(params, grads_ic)
    g_full = _flatten_grads(params, grads_full)
    result = _grad_metrics(g_ic, g_full)
    result["per_parameter_block_norm_ic"] = _block_norms(trainer.air_net, grads_ic)
    result["per_parameter_block_norm_full"] = _block_norms(trainer.air_net, grads_full)
    result["loss_ic"] = float(loss_ic.detach())
    result["loss_full"] = float(loss_full.detach())
    return result, g_ic, g_full


def _sensitivity_record(net, scales, zeta_points, field_r0):
    records = []
    for zeta_value in zeta_points:
        zeta = torch.full((1, 1), float(zeta_value), dtype=torch.float64)
        for r0_value in field_r0:
            r0 = torch.tensor([[float(r0_value)]], dtype=torch.float64,
                              requires_grad=True)
            t = torch.zeros_like(r0)
            fields = net(
                zeta, t, r0, scales,
                time_input=TimeInput(0.0, 1.0),
            )
            values = {}
            grads = {}
            for name, value, scale in (
                ("rho", fields.density, scales.rho),
                ("u", fields.velocity, scales.u),
                ("p", fields.pressure, scales.p),
            ):
                normalized = value / float(scale)
                values[name] = float(normalized.detach())
                grads[name] = float(torch.autograd.grad(
                    normalized.sum(), r0, retain_graph=True
                )[0])
            # Central finite difference in physical R0.
            h = 1.0e-5
            fd = {}
            with torch.no_grad():
                for name, scale in (
                    ("rho", scales.rho), ("u", scales.u), ("p", scales.p)
                ):
                    plus_r0 = torch.tensor([[float(r0_value) + h]], dtype=torch.float64)
                    minus_r0 = torch.tensor([[float(r0_value) - h]], dtype=torch.float64)
                    plus = net(zeta, torch.zeros_like(plus_r0), plus_r0,
                               scales, time_input=TimeInput(0.0, 1.0))
                    minus = net(zeta, torch.zeros_like(minus_r0), minus_r0,
                                scales, time_input=TimeInput(0.0, 1.0))
                    plus_v = plus.density if name == "rho" else (
                        plus.velocity if name == "u" else plus.pressure
                    )
                    minus_v = minus.density if name == "rho" else (
                        minus.velocity if name == "u" else minus.pressure
                    )
                    fd[name] = float(
                        (plus_v - minus_v) / (2.0 * h) / float(scale)
                    )
            records.append({
                "zeta": float(zeta_value),
                "r0_m": float(r0_value),
                "normalised": values,
                "d_normalised_d_r0_autograd": grads,
                "d_normalised_d_r0_finite_difference": fd,
                "abs_difference": {
                    name: abs(grads[name] - fd[name]) for name in FIELDS
                },
            })
    return records


def _style_axis(ax):
    ax.grid(True, color=COLORS["grid"], linewidth=0.6, alpha=0.7)
    ax.set_axisbelow(True)
    for spine in ("top", "right"):
        ax.spines[spine].set_visible(False)
    for spine in ("left", "bottom"):
        ax.spines[spine].set_color(COLORS["axis"])
    ax.tick_params(colors=COLORS["secondary"], labelsize=8)


def _plot_curves(records, actual_r0, output: Path):
    fig, axes = plt.subplots(
        3, len(ZETA_POINTS), figsize=(11.5, 8.2),
        sharex=True, constrained_layout=True,
    )
    for col, zeta in enumerate(ZETA_POINTS):
        for row, field in enumerate(FIELDS):
            ax = axes[row, col]
            ax.axvspan(0.05, 0.50, color=COLORS["train_band"], alpha=0.55,
                       linewidth=0)
            ax.axvspan(0.55, 1.00, color=COLORS["val_band"], alpha=0.8,
                       linewidth=0)
            ax.axhline(1.0, color=COLORS["target"], linewidth=1.2,
                       linestyle=(0, (4, 3)), label="theory IC")
            for model in ("B_last", "B_best"):
                rows = [
                    r for r in records[model]
                    if r["zeta"] == zeta
                ]
                x = [r["r0_m"] for r in rows]
                y = [r["normalised"][field] for r in rows]
                ax.plot(
                    x, y, color=COLORS[model], linewidth=1.8,
                    label=model, marker="o", markersize=3.6,
                    markeredgewidth=0,
                )
            _style_axis(ax)
            ax.set_xlim(0.02, 1.03)
            if row == 0:
                ax.set_title(f"zeta = {zeta:g}", fontsize=10,
                             color=COLORS["ink"])
            if col == 0:
                ax.set_ylabel(f"normalized {field}", fontsize=9,
                              color=COLORS["ink"])
            if row == len(FIELDS) - 1:
                ax.set_xlabel("physical charge radius R0 (m)", fontsize=9,
                              color=COLORS["ink"])
    handles, labels = axes[0, 0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", ncol=3, frameon=False,
               bbox_to_anchor=(0.5, 1.035), fontsize=9)
    fig.suptitle(
        "AirNet at t=t0 (similarity x_t=0), fixed internal zeta\n"
        "shaded: training R0 0.05-0.50 (left), validation R0 0.55-1.00 (right)",
        fontsize=11, color=COLORS["ink"], y=1.075,
    )
    fig.savefig(output, dpi=190, bbox_inches="tight")
    plt.close(fig)


def _plot_derivatives(records, output: Path):
    fig, axes = plt.subplots(
        3, len(ZETA_POINTS), figsize=(11.5, 8.2),
        sharex=True, constrained_layout=True,
    )
    for col, zeta in enumerate(ZETA_POINTS):
        for row, field in enumerate(FIELDS):
            ax = axes[row, col]
            ax.axvspan(0.05, 0.50, color=COLORS["train_band"], alpha=0.55,
                       linewidth=0)
            ax.axvspan(0.55, 1.00, color=COLORS["val_band"], alpha=0.8,
                       linewidth=0)
            for model, marker in (("B_last", "o"), ("B_best", "s")):
                rows = [r for r in records[model] if r["zeta"] == zeta]
                x = [r["r0_m"] for r in rows]
                y = [r["d_normalised_d_r0_autograd"][field] for r in rows]
                yfd = [r["d_normalised_d_r0_finite_difference"][field] for r in rows]
                ax.plot(x, y, color=COLORS[model], linewidth=1.6,
                        label=f"{model} autograd")
                ax.plot(x, yfd, linestyle="none", marker=marker, markersize=4.2,
                        markerfacecolor="none", markeredgecolor=COLORS[model],
                        markeredgewidth=1.0,
                        label=f"{model} central FD")
            _style_axis(ax)
            ax.set_xlim(0.02, 1.03)
            if row == 0:
                ax.set_title(f"zeta = {zeta:g}", fontsize=10,
                             color=COLORS["ink"])
            if col == 0:
                ax.set_ylabel(f"d(normalized {field})/dR0 (1/m)",
                              fontsize=8, color=COLORS["ink"])
            if row == len(FIELDS) - 1:
                ax.set_xlabel("physical charge radius R0 (m)", fontsize=9,
                              color=COLORS["ink"])
    handles, labels = axes[0, 0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", ncol=4, frameon=False,
               bbox_to_anchor=(0.5, 1.045), fontsize=8)
    fig.suptitle(
        "R0 sensitivity at t=t0: autograd vs central finite difference",
        fontsize=11, color=COLORS["ink"], y=1.075,
    )
    fig.savefig(output, dpi=190, bbox_inches="tight")
    plt.close(fig)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--output",
        default="outputs/fullframes/time_input_experiment/factor_checks",
    )
    parser.add_argument(
        "--skip-gradients", action="store_true",
        help="compute only the t0/R0 sensitivity curves",
    )
    args = parser.parse_args(argv)
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)

    trainer, _ = diag._build_trainer(CONFIG)
    all_cases = list(trainer.cases) + list(trainer.validation_cases)
    train_cases = list(trainer.cases)
    actual_r0 = [float(case.charge_radius_m) for case in all_cases]

    # Fixed official-sampler batches.  They are generated before any checkpoint
    # is loaded, with explicit seeds, and use only trainer.cases.
    batches = []
    if not args.skip_gradients:
        for seed in BATCH_SEEDS:
            generator = torch.Generator().manual_seed(int(seed))
            batches.append({
                "seed": int(seed),
                "batches": trainer._batches(generator=generator),
            })
        for item in batches:
            item["sha256"] = _batch_hash(item["batches"])

    sensitivity = {}
    derivative_check = {}
    gradient_records = {}
    loss_records = {}

    for model, path in CHECKPOINTS.items():
        trainer.load(path)
        net = trainer.air_net
        # Output scales are identical for all current cases; use case 0 and
        # record the check in initial_input_checks.json.
        sensitivity_scales = trainer._scales[all_cases[0].case_id]
        records = _sensitivity_record(
            net, sensitivity_scales, ZETA_POINTS, actual_r0
        )
        sensitivity[model] = records
        derivative_check[model] = {
            "max_abs_autograd_minus_fd": max(
                row["abs_difference"][field]
                for row in records for field in FIELDS
            ),
            "max_relative_autograd_minus_fd": max(
                row["abs_difference"][field]
                / max(abs(row["d_normalised_d_r0_autograd"][field]), 1.0e-12)
                for row in records for field in FIELDS
            ),
            "n_points": len(records) * len(FIELDS),
        }
        if not args.skip_gradients:
            model_grads = {}
            model_losses = {}
            all_g_ic = []
            all_g_full = []
            for item in batches:
                loop = int(trainer.loop)
                lambda_pde, lambda_data, per_case = _air_terms(
                    trainer, item["batches"], loop
                )
                loss_rec = _loss_record(lambda_pde, lambda_data, per_case)
                grad_rec, g_ic, g_full = _gradient_record(trainer, per_case)
                model_losses[str(item["seed"])] = loss_rec
                model_grads[str(item["seed"])] = grad_rec
                all_g_ic.append(g_ic)
                all_g_full.append(g_full)
            mean_ic = torch.stack(all_g_ic).mean(dim=0)
            mean_full = torch.stack(all_g_full).mean(dim=0)
            gradient_records[model] = {
                "checkpoint_loop": int(trainer.loop),
                "batches": model_grads,
                "seed_average": _grad_metrics(mean_ic, mean_full),
            }
            loss_records[model] = {
                "checkpoint_loop": int(trainer.loop),
                "batches": model_losses,
            }

    _plot_curves(sensitivity, actual_r0, output / "sensitivity_curves.png")
    _plot_derivatives(sensitivity, output / "sensitivity_derivatives.png")

    t0_summary = {}
    initial_error_path = (
        _REPO_ROOT / "outputs/fullframes/time_input_experiment/initial_error/"
        "initial_error.json"
    )
    if initial_error_path.is_file():
        initial = json.loads(initial_error_path.read_text(encoding="utf-8"))
        for label in ("A_last", "A_best", "B_last", "B_best"):
            t0_summary[label] = initial["theoretical_t0_aggregate"].get(label)

    payload = {
        "protocol": {
            "config": CONFIG,
            "checkpoints": {
                model: {
                    "path": str(path),
                    "sha256": _sha256(path),
                } for model, path in CHECKPOINTS.items()
            },
            "zeta_points": list(ZETA_POINTS),
            "fixed_t": "t=0 with TimeInput(0,1); x_t is exactly zero",
            "normalisation": "rho/rho_scale, u/u_scale, p/p_scale",
            "r0_values_m": actual_r0,
            "training_r0_band_m": [0.05, 0.50],
            "validation_r0_band_m": [0.55, 1.00],
            "batch_seeds": list(BATCH_SEEDS),
            "batch_source": (
                "official AlternatingTrainer._batches sampler and per-case "
                "counts, training cases only; explicit fixed generator seeds; "
                "not historical replay"
            ),
            "loss_schedule": (
                "schedule_weights at each checkpoint loop; IC weight is 1.0"
            ),
            "gradient_scope": (
                "AirNet parameters only; ContactNet is detached exactly as in "
                "the official air update; no Adam step"
            ),
            "no_validation_gradient": True,
        },
        "initial_input_checks": "initial_input_checks.json",
        "sensitivity": sensitivity,
        "derivative_check": derivative_check,
        "gradient": gradient_records,
        "loss": loss_records,
        "theoretical_t0_aggregate_from_existing_report": t0_summary,
        "figures": {
            "curves": "sensitivity_curves.png",
            "derivatives": "sensitivity_derivatives.png",
        },
        "notes": [
            "The curves are a read-only input-sensitivity probe, not a new predictive model.",
            "The validation R0 band is not replaced, clipped or trained on.",
            "Gradient norms and angles are descriptive; they do not by themselves establish causality.",
            "The batches are fixed official-sampler draws, not the exact historical batches of the B run.",
        ],
    }
    out_json = output / "ic_factor_checks.json"
