#!/usr/bin/env python3
"""Read-only factor check for the AirNet initial-condition term.

This script does three things, all with existing B checkpoints and without
training, sampling changes, weight changes or optimizer steps:

1. At t=t0 (so the similarity time argument is exactly zero) and at fixed
   internal zeta, plot normalized rho/u/p versus the physical charge radius
   R0.  Training and validation R0 bands are shaded.  The analytical target
   is the separated-air state (normalized value 1.0).
2. Differentiate the normalized prediction with respect to R0 and compare
   autograd with a central finite difference.
3. On three explicitly fixed batches generated by the official training
   sampler (training cases only), report the AirNet IC loss contribution, the
   gradient of that term, and its relation to the full AirNet-stage gradient.
   No Adam step is taken.  Validation cases are used only for scoring, never
   for a gradient.
"""
